#!/usr/bin/env node
// register.mjs - (re)writes src/videos/registry.ts from every src/videos/<slug>/index.tsx that has a timeline.json.
import fs from "node:fs";
import path from "node:path";
import { STUDIO, compId } from "./lib/bundle.mjs";

const dir = path.join(STUDIO, "src", "videos");
const slugs = fs
  .readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(dir, d.name, "index.tsx")) && fs.existsSync(path.join(dir, d.name, "timeline.json")))
  .map((d) => d.name)
  .sort();
const ident = (s) => "V_" + s.replace(/[^a-zA-Z0-9]/g, "_");
const lines = [
  "// AUTO-GENERATED by scripts/register.mjs - lists every video under src/videos/<slug>/index.tsx",
  'import type React from "react";',
  'import type { Timeline } from "../core/types";',
  ...slugs.flatMap((s) => [`import { Video as ${ident(s)} } from "./${s}/index";`, `import ${ident(s)}_T from "./${s}/timeline.json";`]),
  "",
  "export type VideoEntry = { id: string; component: React.FC<{ variant?: number }>; timeline: Timeline };",
  "export const VIDEOS: VideoEntry[] = [",
  ...slugs.map((s) => `  { id: "${compId(s)}", component: ${ident(s)}, timeline: ${ident(s)}_T as unknown as Timeline },`),
  "];",
  "",
];
fs.writeFileSync(path.join(dir, "registry.ts"), lines.join("\n"));
console.log(`registry: ${slugs.length} video(s): ${slugs.map(compId).join(", ") || "(none)"}`);
